#!/usr/bin/env python3
"""Regenerate the hold-to-lead rule in .config/karabiner/karabiner.json.

Ghostty only: right ⌘ / right ⌥ act like modifiers for the tmux prefix / nvim
leader — hold one and every key pressed meanwhile is sent as C-Space <key> /
Space <key> (release in any order; press more keys while held to chain binds).
Outside ghostty, both are plain ⌘ / ⌥.

Karabiner can't echo the "from" key in "to", hence one manipulator per key and
modifier (plain / ⇧ / ⌃). Covers every key, so bind changes need no re-run.
Karabiner reloads the file on change.
"""
import json
from pathlib import Path

CONFIG = Path(__file__).resolve().parent.parent / ".config/karabiner/karabiner.json"
MARK = "Generated by scripts/karabiner-hold-leaders.py"  # rule is found by this description suffix
TERMINALS = ["^com\\.mitchellh\\.ghostty$"]
LEADERS = [  # (held key, variable, key sent before each key)
    ("right_command", "rcmd_tmux_prefix", {"key_code": "spacebar", "modifiers": ["left_control"]}),
    ("right_option", "ropt_nvim_leader", {"key_code": "spacebar"}),
]
KEYS = (
    list("abcdefghijklmnopqrstuvwxyz1234567890")
    + ["hyphen", "equal_sign", "open_bracket", "close_bracket", "backslash",
       "semicolon", "quote", "grave_accent_and_tilde", "comma", "period", "slash",
       "tab", "spacebar", "return_or_enter",
       "left_arrow", "right_arrow", "up_arrow", "down_arrow"]
)


def key(var, lead, k, mod):
    frm, to = {"key_code": k}, {"key_code": k, "repeat": False}  # held key mustn't auto-repeat without the leader
    if mod:
        frm["modifiers"] = {"mandatory": [mod]}
        to["modifiers"] = [f"left_{mod}"]
    return {
        "type": "basic",
        "conditions": [{"type": "variable_if", "name": var, "value": 1}],
        "from": frm,
        "to": [lead, to],
    }


manipulators = []
for held, var, lead in LEADERS:
    manipulators.append({
        "type": "basic",
        "conditions": [{"type": "frontmost_application_if", "bundle_identifiers": TERMINALS}],
        "from": {"key_code": held, "modifiers": {"optional": ["any"]}},
        "to": [{"set_variable": {"name": var, "value": 1}}],
        "to_after_key_up": [{"set_variable": {"name": var, "value": 0}}],
    })
    manipulators += [key(var, lead, k, mod) for k in KEYS for mod in ("shift", "control", None)]

rule = {
    "description": "Ghostty: hold right ⌘ / right ⌥ + keys = tmux prefix (C-Space) / nvim leader (Space) "
                   f"before each key, chainable. {MARK}",
    "manipulators": manipulators,
}

cfg = json.loads(CONFIG.read_text())
rules = cfg["profiles"][0]["complex_modifications"]["rules"]
i = next(i for i, r in enumerate(rules) if r["description"].endswith(MARK))
rules[i] = rule
CONFIG.write_text(json.dumps(cfg, indent=4, ensure_ascii=False) + "\n")
print(f"wrote {len(manipulators)} manipulators to {CONFIG}")
